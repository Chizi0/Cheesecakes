const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const html = fs.readFileSync('rxbridge/index.html','utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'app script exists');
const root={value:'patient'};
const content={innerHTML:''};
const nodes={role:root,content,reset:{addEventListener(){}}};
const document={getElementById(id){return nodes[id]||null},querySelectorAll(){return []}};
root.addEventListener=()=>{};
const context=vm.createContext({document,structuredClone,alert:()=>{},confirm:()=>true,prompt:()=>''});
vm.runInContext(script,context);
const run=s=>vm.runInContext(s,context);
assert.match(content.innerHTML,/Patient tracking/);
run('document.getElementById("role").value="prescriber";render()');
assert.match(content.innerHTML,/Create simulated prescription/);
run('createOrder({patient:"Alex Sample",medication:"Demo Medication C",pharmacy:"Sample Pharmacy"})');
assert.equal(run('orders[0].status'),'received');
run('advanceOrder("RX-1003","processing")');
run('advanceOrder("RX-1003","ready")');
run('advanceOrder("RX-1003","picked up")');
assert.equal(run('orders[0].status'),'picked up');
run('requestTransfer("RX-1002","north","delivery")');
assert.equal(run('orders[2].transfer.approvedByPatient'),true);
assert.throws(()=>run('advanceOrder("RX-1002","processing")'),/pending transfer/);
run('reviewTransfer("RX-1002",true)');
assert.equal(run('orders[2].transfer.status'),'awaiting prescriber or authorized transfer review');
run('finalizeTransfer("RX-1002")');
assert.equal(run('orders[2].pharmacy'),'Northside Pharmacy');
assert.equal(run('orders[2].status'),'received');
run('advanceOrder("RX-1001","delayed","Stock unavailable")');
assert.throws(()=>run('requestTransfer("RX-1001","park","delivery")'),/Invalid pharmacy or fulfillment choice/);
run('advanceOrder("RX-1002","processing")');
run('advanceOrder("RX-1002","ready")');
assert.equal(run('orders[2].status'),'ready');
run('requestTransfer("RX-1001","north","pickup")');
run('reviewTransfer("RX-1001",false)');
assert.equal(run('orders[1].transfer'),null);
run('requestTransfer("RX-1001","park","pickup")');
assert.equal(run('orders[1].transfer.target'),'Park Avenue Pharmacy');
console.log('PASS: 15 simulated workflow assertions');
